#!/bin/bash

[ -d gh-pages ] || git clone -q --branch gh-pages $(git config --get remote.origin.url) gh-pages
cd gh-pages

function checkCount() {
  local content="$1"
  local count="$2"
  local minimum="$3"

  if [ $count -lt $minimum ]
  then
    echo "!!! failing because low packages count for $content: $count (probably intermittent download failure)"
    exit 1
  fi
}

function updateIndex() {
  local d=$1

  (
    mkdir -p $d/simple
    cd $d/simple

    curl -s https://download.pytorch.org/$d/ | grep -v 'TIMESTAMP 1' > index.html
    local count="$(cat index.html | cut -d '>' -f 2 | cut -d '<' -f 1 | grep -cve '^\s*$')"

    echo "Fetching https://download.pytorch.org/$d/ => $d/simple/"
    checkCount $d $count 40

    local i=0
    for p in `cat index.html | cut -d '>' -f 2 | cut -d '<' -f 1`
    do
      mkdir -p $p
      cd $p
      ((i++))
      curl -s https://download.pytorch.org/$d/$p/ \
        | sed -e 's_href="/whl_href="https://download.pytorch.org/whl_' \
        | grep -v 'TIMESTAMP 1' \
        > index.html

      local pcount="$(cat index.html | grep -c 'https://download.pytorch.org/whl/')"
      # Reverted to $count to match the original script's behavior for dependencies like certifi
      checkCount $d/$p $count 1
      cd ..
    done
    echo "✅ Completed $d"
  )
}

function updateHumanIndexes() {
  cat <<EOF > whl/index.html
<!DOCTYPE html>
<html>
  <body>
    <h1>Sonatype <a href="https://pytorch.org/">PyTorch</a> PyPI improved indexes for <a href="https://help.sonatype.com/en/pypi-repositories.html#download--search--and-install-packages-using-pip">Nexus Repository</a></h1>

Generated by <a href="https://github.com/83hd4d/pytorch-pypi">83hd4d/pytorch-pypi</a> from <a href="https://download.pytorch.org/whl/">https://download.pytorch.org/whl/</a>
<p>
for the full index, use <code>--index-url <a href="simple">https://83hd4d.github.io/pytorch-pypi/whl/simple</code></a>
<p>
You can also use compute platform filtered indexes:
<ul>
$(for d in whl/*
  do
    d="$(echo $d | cut -c 5-)"
    [ -d "whl/$d" ] && [ "$d" != "simple" ] \
      && echo "<li><a href=\"$d\">$d</a></li>"
  done)
</ul>
</body>
</html>
EOF

  for d in whl/*
  do
    d="$(echo $d | cut -c 5-)"
    [ -d "whl/$d" ] && [ "$d" != "simple" ] \
      && cat <<EOF > whl/$d/index.html
<!DOCTYPE html>
<html>
  <body>
    <h1>Sonatype <a href="https://pytorch.org/">PyTorch</a> PyPI improved indexes for <a href="https://help.sonatype.com/en/pypi-repositories.html#download--search--and-install-packages-using-pip">Nexus Repository</a></h1>

Generated by <a href="https://github.com/83hd4d/pytorch-pypi">83hd4d/pytorch-pypi</a> from <a href="https://download.pytorch.org/whl/$d/">https://download.pytorch.org/whl/$d/</a>
<p>
for $d compute platform index, use <code>--index-url <a href="simple">https://83hd4d.github.io/pytorch-pypi/whl/$d/simple</code></a>
<p>
see also <a href="..">other available indexes</a>
</body>
</html>
EOF
  done
}

# 1. Update main PyTorch index (Sequentially, to check if we even need to continue)
updateIndex "whl"
updateIndex "whl/nightly"

git update-index -q --refresh

if git diff-index --quiet HEAD; then
  echo "no update found in PyTorch main index."
  updateHumanIndexes
  exit 0
fi

echo "Updates found in PyTorch main index. Updating platforms in parallel..."

# 2. Dynamically fetch platforms
DYNAMIC_VERSIONS=$(curl -sS https://download.pytorch.org/whl/ | grep -Eo 'href="(cu[0-9]+|cpu|xpu|rocm[0-9.]+)/?"' | cut -d'"' -f2 | tr -d '/' | sort -u)
echo "Platforms found: $DYNAMIC_VERSIONS"

# 3. PARALLEL EXECUTION: Launch all platforms concurrently
PIDS=()
for d in $DYNAMIC_VERSIONS
do
  updateIndex "whl/$d" & 
  PIDS+=($!)
done

# 4. Wait for all background jobs to finish and ensure none failed
for pid in "${PIDS[@]}"; do
  wait $pid || { echo "!!! A parallel download job failed. Exiting."; exit 1; }
done

updateHumanIndexes

du -sh whl/*

for d in whl/simple whl/*/simple ; do echo "$(ls $d | wc -l | xargs) $d" ; done > summary.txt
cat summary.txt
